CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(128)   NOT NULL,
    type        VARCHAR(16)    NOT NULL,
    currency    VARCHAR(3)     NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total       DECIMAL(19, 2) NOT NULL,
    metadata    JSON           NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_transactions_external_id UNIQUE (external_id),
    CONSTRAINT ck_transactions_type CHECK (type IN ('flight', 'hotel', 'rail', 'navan_fee'))
);

CREATE TABLE transaction_tax_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT         NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    line_no        INT            NOT NULL,
    name           VARCHAR(128)   NOT NULL,
    rate           DECIMAL(9, 6),
    amount         DECIMAL(19, 2) NOT NULL,
    CONSTRAINT uq_tax_line_no UNIQUE (transaction_id, line_no)
);

CREATE TABLE transaction_fee_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT         NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    line_no        INT            NOT NULL,
    name           VARCHAR(128)   NOT NULL,
    amount         DECIMAL(19, 2) NOT NULL,
    CONSTRAINT uq_fee_line_no UNIQUE (transaction_id, line_no)
);

CREATE TABLE invoices (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency   VARCHAR(3)     NOT NULL,
    total      DECIMAL(19, 2) NOT NULL,
    tax_rollup JSON           NOT NULL,
    fee_rollup JSON           NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE invoice_lines (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id       BIGINT   NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    -- RESTRICT: the database itself refuses to delete a billed transaction
    transaction_id   BIGINT   NOT NULL REFERENCES transactions (id) ON DELETE RESTRICT,
    line_no          INT      NOT NULL,
    snapshot_version SMALLINT NOT NULL,
    -- frozen copy of the transaction; never joined back to transactions on read
    snapshot         JSON     NOT NULL,
    CONSTRAINT uq_invoice_line_txn UNIQUE (invoice_id, transaction_id)
);

CREATE INDEX ix_invoice_lines_transaction_id ON invoice_lines (transaction_id);
